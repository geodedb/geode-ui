// Package wsx connection-cap runtime.
//
// GAP-0075 (1/2): pre-handshake WebSocket connection cap surface.
//
// Limiter is a concurrent-safe gate that the genapi-emitted
// RegisterGeneratedWS wrapper consults BEFORE invoking
// wsx.UpgradeStrict. A rejected client sees an HTTP 503 +
// Retry-After response before the WebSocket handshake completes
// (~10x cheaper than the post-handshake 1013 close-frame
// scope-fallback that freedom-go's pkg/freedomshared/wsx.HoldOpenLimited
// shipped before this generator-side fix landed).
//
// Defaults mirror the freedom-go scope-fallback: 1024 concurrent
// connections per pod, 4 connections per remote IP, 60 upgrades per
// IP per minute. Operators override via env:
//
//	WS_MAX_CONNECTIONS=1024
//	WS_MAX_CONNECTIONS_PER_IP=4
//	WS_UPGRADE_RATE_PER_MIN=60
//
// A value of 0 (env unset) keeps the default. Setting any field to a
// negative value disables that knob (used by tests).
//
// Limiter intentionally has no OpenTelemetry dependency. The
// generator-side wrapper (cmd/genapi/templates/ws.go.tmpl) is the
// surface that emits OTel span attributes and the obsx counter; this
// package stays import-clean so any consumer can wire its own
// observability layer.

// Code generated by genapi; DO NOT EDIT.
package wsx

import (
	"errors"
	"net"
	"os"
	"strconv"
	"strings"
	"sync"
	"time"
)

// Sentinel errors returned by Limiter.Acquire on rejection. Each
// rejection class is independently identifiable via errors.Is so the
// genapi wrapper can attribute the rejection (Retry-After value, OTel
// reason label, obsx counter dimension).
var (
	// ErrTotalCap is returned when the pod-wide concurrent-WS cap
	// (Config.MaxConnections / DefaultMaxConnections) is reached.
	ErrTotalCap = errors.New("ws upgrade rejected: pod connection cap")
	// ErrPerIPCap is returned when the per-remote-IP concurrent-WS
	// cap (Config.MaxConnectionsPerIP / DefaultMaxConnectionsPerIP)
	// is reached.
	ErrPerIPCap = errors.New("ws upgrade rejected: per-IP connection cap")
	// ErrRateCap is returned when the per-IP rolling-minute upgrade
	// rate cap (Config.UpgradeRatePerMin / DefaultUpgradeRatePerMin)
	// is exceeded.
	ErrRateCap = errors.New("ws upgrade rejected: per-IP rate cap")
)

// Defaults exported so tests + per-service main.go bootstraps can
// reference them without re-spelling the numbers.
const (
	DefaultMaxConnections      = 1024
	DefaultMaxConnectionsPerIP = 4
	DefaultUpgradeRatePerMin   = 60
)

// LimiterConfig configures NewLimiter.
type LimiterConfig struct {
	// MaxConnections is the total concurrent-WS cap for this pod.
	// Zero defaults to DefaultMaxConnections; negative disables.
	MaxConnections int

	// MaxConnectionsPerIP caps concurrent WS connections from a
	// single remote IP. Zero defaults to DefaultMaxConnectionsPerIP;
	// negative disables.
	MaxConnectionsPerIP int

	// UpgradeRatePerMin caps the number of NEW upgrades from a single
	// remote IP per rolling minute. Defends against misbehaving
	// clients that retry an upgrade in a tight loop. Zero defaults to
	// DefaultUpgradeRatePerMin; negative disables.
	UpgradeRatePerMin int

	// RateWindow is the rolling window across which UpgradeRatePerMin
	// is enforced. Zero defaults to one minute. Exported so tests can
	// shrink the window without having to wait wall-clock time.
	RateWindow time.Duration
}

// LimiterConfigFromEnv reads WS_MAX_CONNECTIONS,
// WS_MAX_CONNECTIONS_PER_IP, and WS_UPGRADE_RATE_PER_MIN from the
// process environment. Missing vars (or invalid integers) fall
// through to the defaults declared above -- a misconfigured cap
// should not take a pod down at startup.
func LimiterConfigFromEnv() LimiterConfig {
	return LimiterConfig{
		MaxConnections:      envInt("WS_MAX_CONNECTIONS", DefaultMaxConnections),
		MaxConnectionsPerIP: envInt("WS_MAX_CONNECTIONS_PER_IP", DefaultMaxConnectionsPerIP),
		UpgradeRatePerMin:   envInt("WS_UPGRADE_RATE_PER_MIN", DefaultUpgradeRatePerMin),
	}
}

func envInt(key string, def int) int {
	v := strings.TrimSpace(os.Getenv(key))
	if v == "" {
		return def
	}
	n, err := strconv.Atoi(v)
	if err != nil {
		// Invalid value -- fall back to default rather than panic at
		// startup. Misconfigured cap should not take a pod down.
		return def
	}
	return n
}

// Limiter is safe for concurrent use across many goroutines.
type Limiter struct {
	cfg LimiterConfig

	mu             sync.Mutex
	total          int
	perIPActive    map[string]int
	perIPUpgrades  map[string][]time.Time
	rateWindowSize time.Duration
	// lastSweep is when sweepLocked last walked perIPUpgrades to delete
	// entries whose every timestamp aged out of the rolling window. The
	// sweep runs opportunistically from Acquire at most once per window,
	// so abandoned IPs cannot grow the map forever (QG-067).
	lastSweep time.Time
	// now is a test clock seam (mirrors jwt_cache.go). nil means time.Now,
	// so production behaviour is unchanged; tests inject a fake clock to
	// drive the rolling window + sweep deterministically without sleeping.
	now func() time.Time
}

// timeNow returns the limiter's current time, honouring the test clock seam.
func (l *Limiter) timeNow() time.Time {
	if l.now != nil {
		return l.now()
	}
	return time.Now()
}

// NewLimiter builds a Limiter. cfg is canonicalised in-place
// (zero-value fields are filled with defaults).
func NewLimiter(cfg LimiterConfig) *Limiter {
	if cfg.MaxConnections == 0 {
		cfg.MaxConnections = DefaultMaxConnections
	}
	if cfg.MaxConnectionsPerIP == 0 {
		cfg.MaxConnectionsPerIP = DefaultMaxConnectionsPerIP
	}
	if cfg.UpgradeRatePerMin == 0 {
		cfg.UpgradeRatePerMin = DefaultUpgradeRatePerMin
	}
	win := cfg.RateWindow
	if win <= 0 {
		win = time.Minute
	}
	return &Limiter{
		cfg:            cfg,
		perIPActive:    make(map[string]int),
		perIPUpgrades:  make(map[string][]time.Time),
		rateWindowSize: win,
		lastSweep:      time.Now(),
	}
}

// Acquire records an upgrade attempt from remoteAddr (raw "host:port"
// or bare host). Returns nil if the upgrade is allowed; a sentinel
// error from {ErrTotalCap, ErrPerIPCap, ErrRateCap} otherwise. On
// non-nil return, the caller MUST NOT call Release.
//
// Acquire is the only mutator in the hot path. Callers in the
// genapi-emitted wrapper invoke Acquire BEFORE wsx.UpgradeStrict so
// rejection costs only an HTTP 503 response, not the full handshake.
func (l *Limiter) Acquire(remoteAddr string) error {
	ip := hostFromAddr(remoteAddr)
	l.mu.Lock()
	defer l.mu.Unlock()

	// Pod-wide cap.
	if l.cfg.MaxConnections > 0 && l.total >= l.cfg.MaxConnections {
		return ErrTotalCap
	}
	// Per-IP concurrent cap.
	if l.cfg.MaxConnectionsPerIP > 0 && l.perIPActive[ip] >= l.cfg.MaxConnectionsPerIP {
		return ErrPerIPCap
	}
	// Per-IP upgrade-rate cap (rolling-window).
	if l.cfg.UpgradeRatePerMin > 0 {
		now := l.timeNow()
		windowStart := now.Add(-l.rateWindowSize)
		// QG-067: amortised sweep so entries for IPs that never come back
		// are eventually deleted instead of accumulating per distinct IP
		// for the life of the process.
		l.sweepLocked(now, windowStart)
		stamps := l.perIPUpgrades[ip]
		trimmed := stamps[:0]
		for _, t := range stamps {
			if t.After(windowStart) {
				trimmed = append(trimmed, t)
			}
		}
		if len(trimmed) >= l.cfg.UpgradeRatePerMin {
			l.perIPUpgrades[ip] = trimmed
			return ErrRateCap
		}
		l.perIPUpgrades[ip] = append(trimmed, now)
	}

	l.total++
	l.perIPActive[ip]++
	return nil
}

// Release decrements the counters for remoteAddr. Must be called
// exactly once per Acquire that returned nil. Safe to call from a
// defer.
func (l *Limiter) Release(remoteAddr string) {
	ip := hostFromAddr(remoteAddr)
	l.mu.Lock()
	defer l.mu.Unlock()
	if l.total > 0 {
		l.total--
	}
	if l.perIPActive[ip] > 0 {
		l.perIPActive[ip]--
	}
	if l.perIPActive[ip] == 0 {
		delete(l.perIPActive, ip)
	}
}

// sweepLocked deletes perIPUpgrades entries whose every timestamp has aged
// out of the rolling window. Caller must hold l.mu. Runs at most once per
// rate window so its O(tracked IPs) cost is amortised across Acquire calls
// (QG-067, #222).
func (l *Limiter) sweepLocked(now, windowStart time.Time) {
	if now.Sub(l.lastSweep) < l.rateWindowSize {
		return
	}
	l.lastSweep = now
	for ip, stamps := range l.perIPUpgrades {
		live := false
		for _, t := range stamps {
			if t.After(windowStart) {
				live = true
				break
			}
		}
		if !live {
			delete(l.perIPUpgrades, ip)
		}
	}
}

// Snapshot returns a point-in-time view of the limiter state. Used
// by metrics exporters and tests.
type Snapshot struct {
	TotalActive   int
	PerIPActive   map[string]int
	UpgradeWindow time.Duration
}

// Snapshot returns a copy-safe view of the current state.
func (l *Limiter) Snapshot() Snapshot {
	l.mu.Lock()
	defer l.mu.Unlock()
	out := Snapshot{
		TotalActive:   l.total,
		UpgradeWindow: l.rateWindowSize,
		PerIPActive:   make(map[string]int, len(l.perIPActive)),
	}
	for k, v := range l.perIPActive {
		out.PerIPActive[k] = v
	}
	return out
}

