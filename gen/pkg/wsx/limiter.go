// RateWindow returns the rolling window used by the rate cap. The
// genapi-emitted wrapper uses this to compute a Retry-After hint
// when ErrRateCap fires.
func (l *Limiter) RateWindow() time.Duration {
	return l.rateWindowSize
}

// hostFromAddr splits "host:port" into "host". Returns the input
// unchanged when SplitHostPort fails (so a caller passing a bare IP
// still keys correctly).
func hostFromAddr(addr string) string {
	if addr == "" {
		return ""
	}
	host, _, err := net.SplitHostPort(addr)
	if err != nil {
		return addr
	}
	return host
}

// processLimiter caches the env-derived Limiter for the lifetime of
// the process. ProcessLimiter is the consumed-by-the-generated-wrapper
// convenience entry point so each service shell adds only one line
// (`limiter := wsx.ProcessLimiter()`) rather than owning its own
// sync.Once / package-level var.
var (
	processLimiterOnce sync.Once
	processLimiter     *Limiter
)

// ProcessLimiter returns the lazily-built process-singleton Limiter,
// configured from environment variables (LimiterConfigFromEnv). All
// WS endpoints in a given binary share the same limiter so a single
// misbehaving client cannot fan its WS retries across paths to
// multiply its effective cap.
func ProcessLimiter() *Limiter {
	processLimiterOnce.Do(func() {
		processLimiter = NewLimiter(LimiterConfigFromEnv())
	})
	return processLimiter
}
