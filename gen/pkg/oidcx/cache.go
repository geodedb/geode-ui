// JWKCache is an auto-refreshing JWK Set cache. The zero value is not
// usable; construct one with [NewJWKCache].
type JWKCache struct {
	ar           *jwk.Cache
	url          string
	maxStaleness time.Duration
	logger       Logger

	// lastFreshAt is the unix-nano timestamp of the most recent
	// successful JWKS fetch as observed by the instrumented HTTP
	// client. Used to enforce [WithMaxStaleness]. APPSEC-3.
	lastFreshAt atomic.Int64
}

// instrumentedHTTPClient adapts the caller-supplied [HTTPClient] (which
// uses *http.Request / Do semantics, matching *http.Client) to jwx v2's
// httprc.HTTPClient contract (Get(string)). It also bumps a freshness
// timestamp once a 2xx response body successfully parses as a non-empty
// JWK Set. The cache uses this to enforce the max-staleness cap
// (APPSEC-3) without relying on jwk.Cache's internal state, which is
// not exposed.
//
// APPSEC-13: validating the body (rather than trusting any 2xx) is
// load-bearing for the staleness cap. A degraded-but-not-down IdP
// can return 200 OK with malformed JWK content; without the parse
// gate the cache would silently treat that as a successful refresh
// and indefinitely bypass WithMaxStaleness.
//
// The Get(string) method is required to satisfy the v2 httprc.HTTPClient
// interface that jwx v2's jwk.Cache invokes for each refresh.
type instrumentedHTTPClient struct {
	inner     HTTPClient
	onSuccess func()
	bodyCap   int64
}

// jwksMaxResponseBytes caps the body size we are willing to read for
// the JWK Set parse check. JWK sets are tiny (typically <10 KiB);
// 512 KiB is a generous defensive ceiling against a malicious IdP
// streaming a huge body just to drain memory.
const jwksMaxResponseBytes int64 = 512 * 1024

// Get implements httprc.HTTPClient. jwx v2's jwk.Cache uses this entry
// point for both the initial Register/Refresh fetch and every scheduled
// refresh thereafter.
//
// The httprc.HTTPClient interface does not expose a context to its
// callers, so we attach context.Background() here. The inner client's
// timeout (set in NewJWKCache via WithFetchTimeout) still bounds the
// request, and refresh cancellation flows through jwk.Cache's own
// context (passed at NewCache time).
//
//nolint:noctx // upstream httprc.HTTPClient.Get(string) has no ctx param.
func (c *instrumentedHTTPClient) Get(u string) (*http.Response, error) {
	req, err := http.NewRequestWithContext(context.Background(), http.MethodGet, u, nil)
	if err != nil {
		return nil, err
	}
	return c.do(req)
}

// do issues the request through the caller-supplied inner client and
// applies the freshness parse-gate before returning the response to
// jwk.Cache for JWK Set decoding.
func (c *instrumentedHTTPClient) do(r *http.Request) (*http.Response, error) {
	resp, err := c.inner.Do(r)
	if err != nil || resp == nil {
		return resp, err
	}
	if resp.StatusCode < 200 || resp.StatusCode >= 300 {
		return resp, nil
	}
	limit := c.bodyCap
	if limit <= 0 {
		limit = jwksMaxResponseBytes
	}
	body, readErr := io.ReadAll(io.LimitReader(resp.Body, limit))
	_ = resp.Body.Close()
	resp.Body = io.NopCloser(bytes.NewReader(body))
	if readErr != nil {
		return resp, nil
	}
	// Parse-gate: a 200 OK with malformed JWK content (CWE-754) must
	// not advance freshness. APPSEC-13.
	parsed, parseErr := jwk.Parse(body)
	if parseErr != nil || parsed == nil || parsed.Len() == 0 {
		return resp, nil
	}
	if c.onSuccess != nil {
		c.onSuccess()
	}
	return resp, nil
}

// ErrEmptyJWKSet is returned by [NewJWKCache] when the IdP responds with
// a parseable but empty JWK set on cold start. Callers should treat this
// as a misconfiguration of the JWKS endpoint.
var ErrEmptyJWKSet = errors.New("oidcx: jwks endpoint returned no keys")

