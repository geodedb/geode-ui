// Package ratebucket is the canonical mutex-guarded token bucket shared by the
// rate-limiters that previously each carried a byte-identical private copy of
// this algorithm (securex.Bucket, mcpx's bucket, httpx's tokenBucket) —
// QG-046/QG-059/PERF-0044. Consumers that need different semantics keep their
// own type: httpx.PeerLimiter (per-IP map + TTL eviction), htpx.rateBucket
// (lock-free int64/atomic), and wsx.Limiter (sliding-window connection limiter)
// are deliberately NOT folded in — they are different algorithms, not copies.
// Code generated by genapi; DO NOT EDIT.
package ratebucket

import (
	"context"
	"sync"
	"time"
)

// Bucket is a classic token bucket: tokens refill at `rate` per second up to a
// ceiling of `burst`, and each admitted call consumes one token. Safe for
// concurrent use.
type Bucket struct {
	mu          sync.Mutex
	tokens      float64
	last        time.Time
	rate, burst float64
}

// New creates a bucket pre-filled to burst with the given rate and burst.
func New(rate, burst float64) *Bucket {
	return &Bucket{tokens: burst, last: time.Now(), rate: rate, burst: burst}
}

// refillLocked advances the token count for elapsed time. Caller holds b.mu.
func (b *Bucket) refillLocked(now time.Time) {
	dt := now.Sub(b.last).Seconds()
	b.tokens += dt * b.rate
	if b.tokens > b.burst {
		b.tokens = b.burst
	}
	b.last = now
}

// Allow returns true if a token is available and consumes one.
func (b *Bucket) Allow() bool {
	b.mu.Lock()
	defer b.mu.Unlock()
	b.refillLocked(time.Now())
	if b.tokens >= 1 {
		b.tokens -= 1
		return true
	}
	return false
}

// Snapshot returns an approximate (limit, remaining, resetTime) for headers
// without consuming a token.
func (b *Bucket) Snapshot() (int, int, time.Time) {
	b.mu.Lock()
	defer b.mu.Unlock()
	return int(b.burst), int(b.tokens), time.Now().Add(time.Second)
}

// Snap is the value form of (limit, remaining, resetTime).
type Snap struct {
	Limit     int
	Remaining int
	Reset     time.Time
}

// AllowAndSnapshot performs the admit decision and captures the snapshot under
// a single lock acquisition. A canceled context short-circuits to denied
// without taking the lock (the caller has already blown its deadline).
func (b *Bucket) AllowAndSnapshot(ctx context.Context) (allowed bool, snap Snap) {
	if ctx != nil {
		if err := ctx.Err(); err != nil {
			return false, Snap{}
		}
	}
	b.mu.Lock()
	defer b.mu.Unlock()
	now := time.Now()
	b.refillLocked(now)
	if b.tokens >= 1 {
		b.tokens -= 1
		allowed = true
	}
	snap = Snap{Limit: int(b.burst), Remaining: int(b.tokens), Reset: now.Add(time.Second)}
	return allowed, snap
}
