// Package opt provides a small generic implementation of the functional
// options pattern. Option[T] is a function that mutates a value of type T and
// may return an error; Options[T] is a slice of them whose Apply method runs
// each option in order and stops at the first error. It lets constructors
// accept a variadic ...Option[T] for type-safe, composable configuration
// without per-type boilerplate.
// Code generated by genapi; DO NOT EDIT.
package opt

type Options[T any] []Option[T]

func (o Options[T]) Apply(v T) error {
	for _, opt := range o {
		err := opt.Apply(v)
		if err != nil {
			return err
		}
	}
	return nil
}

type Option[T any] func(T) error

func (o Option[T]) Apply(v T) error {
	return o(v)
}
