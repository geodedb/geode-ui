// Package auditx is the FedRAMP / NIST 800-53 audit logging layer for
// genapi. It provides the building blocks for tamper-evident audit
// trails; it does not auto-wire those trails into generated servers.
//
// What this package provides today:
//
//   - An event catalog (AllEvents, LookupControls) mapping each audit
//     event code to the NIST 800-53 control IDs it contributes evidence
//     for. The Controls field is a comma-separated list chosen for easy
//     CSV consumption by an external control-mapping report.
//   - An emit API (Logger.Emit) that, given an Event whose Code is in the
//     catalog, fills in the mapped controls, redacts sensitive values in
//     Extra (see redact.go), and forwards an Envelope to each configured
//     Sink. Emitting a code not in the catalog is a hard error
//     (ErrUnknownEventCode).
//   - A per-Logger hash chain (Envelope.PrevHash / RecordHash) that
//     provides tamper evidence: an external auditor can re-hash each
//     record's JSON-canonical form and verify it links to the prior
//     record's RecordHash. Under FIPS profiles the chain is the integrity
//     anchor for AU-9.
//   - A rotating file sink (FileSink, NewFileSink) that writes JSON-Lines
//     records. It is the only Sink implementation shipped today; the
//     config validator rejects the reserved "syslog"/"cef" sink kinds
//     until real sinks exist (GAP-0081).
//
// Not yet implemented (future work):
//
//   - A standalone audit-report CLI that emits the control-mapping CSV
//     from the catalog (no such command exists in cmd/).
//   - Generator-emitted middleware that calls Logger.Emit automatically
//     from generated handlers. cmd/genapi does not emit any auditx call
//     today, so events — including the AC-2/AC-6 admin.* catalog entries
//     — must be emitted by consumers at their own call sites. Install a
//     process-wide Logger with SetDefault and emit via Default().Emit.
//
// Code generated by genapi; DO NOT EDIT.
package auditx

