// LookupControls returns the 800-53 control list for code, or false when
// the code is not in the catalog.
func LookupControls(code string) (string, bool) {
	for _, e := range catalog {
		if e.Code == code {
			return e.Controls, true
		}
	}
	return "", false
}

// AllEvents returns a copy of the catalog. Callers that mutate this slice
// do not affect the package state.
func AllEvents() []CatalogEntry {
	out := make([]CatalogEntry, len(catalog))
	copy(out, catalog)
	return out
}
