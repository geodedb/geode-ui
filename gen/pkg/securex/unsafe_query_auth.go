package securex

import "net/http"

// UnsafeQueryAuthPolicy reproduces the legacy permissive query-token behavior.
//
// Deprecated: query-string credentials leak via logs/proxies/history.
// Use DefaultRequestAuthPolicy and configure a header- or
// subprotocol-based transport instead. Gated behind the
// `unsafe_query_auth_policy` build tag to prevent accidental linkage.
func UnsafeQueryAuthPolicy() RequestAuthPolicy {
	policy := DefaultRequestAuthPolicy()
	policy.AllowQueryBearer = true
	policy.AllowQuerySignature = true
	return policy
}

// RequestWithQueryAuth preserves the legacy permissive behavior. Prefer
