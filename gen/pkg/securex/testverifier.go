package securex

import (
	"net/http"
	"strings"
	"testing"
)

// NewTestVerifier returns an Auth-style request verifier that accepts any
// request carrying a non-empty `Authorization: Bearer <token>` header.
// Empty Authorization headers, malformed headers, and missing tokens all
// return ErrAuthFailed.
//
// The returned function is intended for unit-test ergonomics ONLY. It
// does not validate the bearer token; any non-empty value passes.
// Production code MUST NOT wire this verifier -- the genapi-generated
// registration calls explicitly panic with ErrAuthVerifierRequired if
// the caller supplies nil for a route declaring auth: "jwt", which makes
// the "forgot to wire a real verifier" failure mode loud at boot.
//
// Example use in a test:
//
//	api.RegisterGeneratedAPI(mux, srv, api.APIOptions{
//	    AuthJWT: securex.NewTestVerifier(),
//	    Auth:    securex.NewTestVerifier(),
//	})
//
// The same function value satisfies both APIKey and JWT verifier slots
// because both contracts are `func(*http.Request) error`.
func NewTestVerifier() func(*http.Request) error {
	// APPSEC-Gen-F-008: fail-loud guard. NewTestVerifier is shipped in
	// production source so genapi-rendered harnesses can import it, but
	// a production binary MUST NEVER reach this path. testing.Testing()
	// returns true only when the binary was built by `go test`; any
	// other call site (a production main reaching here by typo or
	// accidental wiring) panics at construction.
	if !testing.Testing() {
		panic("securex.NewTestVerifier called outside go test — production code must wire a real verifier (see ErrAuthVerifierRequired)")
	}
	return func(r *http.Request) error {
		if r == nil {
			return ErrAuthFailed
		}
		auth := strings.TrimSpace(r.Header.Get("Authorization"))
		if auth == "" {
			return ErrAuthFailed
		}
		parts := strings.Fields(auth)
		if len(parts) != 2 || !strings.EqualFold(parts[0], "Bearer") {
			return ErrAuthFailed
		}
		if strings.TrimSpace(parts[1]) == "" {
			return ErrAuthFailed
		}
		return nil
	}
}
