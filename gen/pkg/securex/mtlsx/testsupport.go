// Package-level test affordances. These helpers are intended to remove
// adoption friction for downstream consumer test suites that want to
// drive the full mtlsx pipeline (chain + EKU + issuer + CRL + OCSP)
// from httptest, where stdlib does not populate
// tls.ConnectionState.VerifiedChains.
//
// They are exported because downstream test code needs them; they are
// safe to call in test code only. The runtime path (Verifier.
// VerifyAndExtractPrincipal) intentionally requires a non-empty
// VerifiedChains for CRL/OCSP signature verification.

// Code generated by genapi; DO NOT EDIT.
package mtlsx

import (
	"crypto/tls"
	"crypto/x509"
	"net/http"
)

// SetVerifiedClientChain attaches a verified client certificate chain to r
// so that mtlsx.Verifier can extract the leaf, issuer, and (for CRL/OCSP
// signature verification) any intermediates / root.
//
// The chain is leaf-first: chain[0] is the client cert; chain[1] (if
// present) is the issuer used for CRL/OCSP checks; further entries are the
// rest of the path up to a root.
//
// Both r.TLS.PeerCertificates and r.TLS.VerifiedChains are populated. The
// runtime code path reads the leaf from PeerCertificates[0] and the issuer
// from VerifiedChains[0][1]; without the second field set, CRL/OCSP
// signature checks would fail with "no issuer in verified chain", which is
// the friction this helper smooths.
//
// Intended for use in *_test.go files. SetVerifiedClientChain does NOT
// perform any chain verification of its own — callers are responsible for
// supplying a chain that represents the state the test wishes to assert.
//
// Closes the A-NEW-3 (VerifiedChains test model) friction noted in
// docs/GENERATOR_BUGS.md.
func SetVerifiedClientChain(r *http.Request, chain []*x509.Certificate) {
	if r == nil || len(chain) == 0 {
		return
	}
	if r.TLS == nil {
		r.TLS = &tls.ConnectionState{}
	}
	// Copy to avoid sharing the caller's slice with VerifiedChains.
	leafFirst := append([]*x509.Certificate(nil), chain...)
	r.TLS.PeerCertificates = leafFirst
	r.TLS.VerifiedChains = [][]*x509.Certificate{append([]*x509.Certificate(nil), chain...)}
}
