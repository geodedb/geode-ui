// Package securex — OIDC asymmetric verifier.
//
// VerifyJWTWithJWKS is the resource-server counterpart to signerx.SignJWT.
// It is the runtime piece that closes the GENERATOR_BUGS.md "OIDC capability
// gap" — see Recommended generator work step (1) "Port/adapt htpx/oidc.go
// JWKS verification into the securex verifier". Specifically:
//
//   - Accepts asymmetric algorithms only (RS256/384/512, ES256/384/512,
//     PS256/384/512). The `none` algorithm and every HMAC family are
//     rejected unconditionally — RFC 7518 alg confusion is the primary
//     practical OIDC attack class and the verifier MUST refuse to even
//     attempt HMAC verification under an asymmetric profile.
//   - Honors the same Require{Expiry,Issuer,Audience} options that
//     VerifyJWTWithOptions does, so OIDC profiles get strict-claim
//     enforcement by default.
//   - Delegates signature verification to jwx v2's jwt.Parse, which is
//     the same library that signerx.SignJWT signs with.
//
// Code generated by genapi; DO NOT EDIT.
package securex

import (
	"context"
	"encoding/base64"
	"encoding/json/v2"
	"errors"
	"strings"

	"github.com/lestrrat-go/jwx/v2/jwa"
	"github.com/lestrrat-go/jwx/v2/jwk"
	"github.com/lestrrat-go/jwx/v2/jws"
	"github.com/lestrrat-go/jwx/v2/jwt"
)

// AllowedAsymmetricAlgs is the default alg allowlist for OIDC asymmetric
// verification. Callers may override via JWKSVerifyOptions.AllowedAlgs;
// in either case `none` and every HMAC alg remain hard-rejected.
var AllowedAsymmetricAlgs = []jwa.SignatureAlgorithm{
	jwa.RS256, jwa.RS384, jwa.RS512,
	jwa.ES256, jwa.ES384, jwa.ES512,
	jwa.PS256, jwa.PS384, jwa.PS512,
	jwa.EdDSA,
}

// ErrJWKSEmpty is returned when the supplied jwk.Set has no keys. A live
// IdP outage that drained the cache is a separable failure mode from
// signature mismatch and worth surfacing distinctly to callers.
var ErrJWKSEmpty = errors.New("securex: jwks empty (no keys to verify against)")

// JWKSVerifyOptions configures VerifyJWTWithJWKS.
type JWKSVerifyOptions struct {
	// Issuer, when non-empty, is matched against the token's `iss` claim.
	Issuer string
	// Audience, when non-empty, is matched against the token's `aud`.
	Audience string

	// RequireExpiry / RequireIssuer / RequireAudience demand presence of
	// the corresponding claim (independent of the string fields' value
	// matching). OIDC profiles should set all three.
	RequireExpiry   bool
	RequireIssuer   bool
	RequireAudience bool

	// AllowedAlgs, when non-empty, overrides AllowedAsymmetricAlgs.
	// `none` and HMAC family algs are rejected regardless of override.
	AllowedAlgs []jwa.SignatureAlgorithm
}

// VerifyJWTWithJWKS parses and verifies a compact JWS token using the
// supplied jwk.Set. Returns the parsed jwt.Token on success, or
// ErrAuthFailed / ErrJWTUnsupported / ErrJWKSEmpty on failure.
//
// The asymmetric-only contract is enforced before signature verification:
// the JWS header `alg` is parsed and compared against the allowlist; any
// `none` or HMAC alg returns ErrJWTUnsupported without touching keys or
// running the underlying jwt.Parse signature path.
func VerifyJWTWithJWKS(_ context.Context, token string, keys jwk.Set, opts JWKSVerifyOptions) (jwt.Token, error) {
	if keys == nil || keys.Len() == 0 {
		return nil, ErrJWKSEmpty
	}
	alg, err := extractAlg(token)
	if err != nil {
		return nil, err
	}
	if !isAsymmetricAlgAllowed(alg, opts.AllowedAlgs) {
		return nil, ErrJWTUnsupported
	}
	// jwt.WithKeySet by default REQUIRES the JWS header to carry a `kid`
	// that matches a key in the set. SignJWT does not always emit a kid
	// (signers built from raw crypto.Signer have no key id to copy in),
	// so the verifier opts the keyset into:
	//   - WithRequireKid(false)         — kid in header is optional;
	//   - WithInferAlgorithmFromKey(true) — let jwx pick alg from key when
	//                                      the JWS header alg isn't matched
	//                                      to a key's `alg` attr.
	// The alg-allowlist guard above already rejected `none`/HMAC, so this
	// only relaxes key-id lookup, not the alg validation.
	parseOpts := []jwt.ParseOption{
		jwt.WithKeySet(keys,
			jws.WithRequireKid(false),
			jws.WithInferAlgorithmFromKey(true),
		),
		jwt.WithValidate(true),
	}
	if iss := strings.TrimSpace(opts.Issuer); iss != "" {
		parseOpts = append(parseOpts, jwt.WithIssuer(iss))
	}
	if aud := strings.TrimSpace(opts.Audience); aud != "" {
		parseOpts = append(parseOpts, jwt.WithAudience(aud))
	}
	tok, err := jwt.Parse([]byte(token), parseOpts...)
	if err != nil {
		return nil, ErrAuthFailed
	}
	if opts.RequireExpiry && tok.Expiration().IsZero() {
		return nil, ErrAuthFailed
	}
	if opts.RequireIssuer && strings.TrimSpace(tok.Issuer()) == "" {
		return nil, ErrAuthFailed
	}
	if opts.RequireAudience && len(tok.Audience()) == 0 {
		return nil, ErrAuthFailed
	}
	return tok, nil
}

// extractAlg returns the `alg` value from the JWS header without
// touching signatures. Returns ErrJWTUnsupported on malformed input.
func extractAlg(token string) (string, error) {
	parts := strings.Split(token, ".")
	if len(parts) != 3 {
		return "", ErrJWTUnsupported
	}
	headJSON, err := base64.RawURLEncoding.DecodeString(parts[0])
	if err != nil {
		return "", ErrJWTUnsupported
	}
	var hdr struct {
		Alg string `json:"alg"`
	}
	if err := json.Unmarshal(headJSON, &hdr); err != nil {
		return "", ErrJWTUnsupported
	}
	return strings.TrimSpace(hdr.Alg), nil
}

// isAsymmetricAlgAllowed enforces the OIDC asymmetric contract:
//
//   - `none` is rejected unconditionally (RFC 8725 §3.1).
//   - every HMAC family alg (HS256/384/512) is rejected unconditionally
//     so alg-confusion attacks (signing an asymmetric public key as if
//     it were an HMAC secret) cannot succeed even if the caller passed
//     a bad allowlist.
//   - otherwise the alg must appear in the override list, or in
//     AllowedAsymmetricAlgs when no override is supplied.
func isAsymmetricAlgAllowed(alg string, override []jwa.SignatureAlgorithm) bool {
	if alg == "" || strings.EqualFold(alg, "none") {
		return false
	}
	upper := strings.ToUpper(alg)
	if strings.HasPrefix(upper, "HS") {
		return false
	}
	allow := override
	if len(allow) == 0 {
		allow = AllowedAsymmetricAlgs
	}
	for _, a := range allow {
		if strings.EqualFold(string(a), alg) {
			return true
		}
	}
	return false
}
