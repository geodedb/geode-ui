package webauthnx

import "net/http"

// RecordingResponseWriter wraps an http.ResponseWriter so a caller can
// later ask whether the wrapped writer committed any response bytes.
// Used by the generated webauthn_authenticate_complete handler to
// suppress a fallback WriteForbidden call when the post-ceremony hook
// already wrote a response AND THEN returned an error.
//
// The wrapper records the call BEFORE forwarding to the inner writer
// so a panic in the inner WriteHeader/Write still leaves Wrote() ==
// true; the handler must assume the wire has been touched.
type RecordingResponseWriter struct {
	http.ResponseWriter
	wrote bool
}

// WrapRecording returns a *RecordingResponseWriter over w. Always
// returns a non-nil wrapper; callers may use its Wrote method
// unconditionally after the wrapped handler returns.
func WrapRecording(w http.ResponseWriter) *RecordingResponseWriter {
	return &RecordingResponseWriter{ResponseWriter: w}
}

// Wrote reports whether WriteHeader or Write have been called on this
// wrapper. Once true, the underlying http.ResponseWriter has either
// committed a status line or buffered body bytes (or both) and any
// subsequent WriteHeader call will trigger net/http's "superfluous
// WriteHeader" warning.
func (r *RecordingResponseWriter) Wrote() bool { return r.wrote }

// WriteHeader records the call and forwards to the wrapped writer.
func (r *RecordingResponseWriter) WriteHeader(status int) {
	r.wrote = true
	r.ResponseWriter.WriteHeader(status)
}

// Write records the call and forwards to the wrapped writer. The byte
// count and error are returned verbatim from the inner Write so
// callers see the underlying writer's contract.
func (r *RecordingResponseWriter) Write(b []byte) (int, error) {
	r.wrote = true
	return r.ResponseWriter.Write(b)
}
