// Package mcpx implements a JSON-RPC 2.0 engine for the Model Context
// Protocol (MCP) over three transports: HTTP, WebSocket, and STDIO.
//
// # Per-transport authentication posture (SEC-0031)
//
// The three transports do NOT share a uniform authentication model. A
// consumer wiring up mcpx MUST understand the posture of each before
// exposing it:
//
//   - HTTP (HandleHTTP): authenticated. Fails CLOSED when no auth verifier
//     is configured (SetAuthVerifier) — every request is rejected with
//     HTTP 401 until a verifier is installed, and a verifier error rejects
//     the request before any dispatch. The verifier may return a
//     request-scoped context (e.g. carrying JWT claims / roles via
//     ContextWithRoles) that is threaded into tool bodies.
//
//   - WebSocket (ServeWS): authenticated. Fails CLOSED identically to HTTP
//     on a nil verifier, and additionally enforces a fail-closed Origin
//     allowlist (SEC-0008): upgrades are rejected with HTTP 403 unless the
//     Origin is allowlisted (SetWSOriginAllowlist) or SetWSAllowAnyOrigin
//     has been explicitly enabled.
//
//   - STDIO (ServeSTDIO / ServeSTDIOWithContext): UNAUTHENTICATED BY
//     DESIGN. The STDIO loop never consults the auth verifier — the STDIO
//     protocol has no *http.Request to verify and no per-message credential
//     channel. Every dispatched tools/call runs with the authority of the
//     local process that owns the server's stdin/stdout.
//
// # STDIO trust boundary
//
// Because ServeSTDIO performs no authentication, it MUST only be exposed
// across a TRUSTED local process boundary — for example a desktop MCP host
// that spawns this binary as a child process and speaks JSON-RPC over the
// child's stdio. Never bridge ServeSTDIO to a network listener, a shared
// pseudo-terminal, or any stream an untrusted party can write to: doing so
// grants that party unauthenticated access to every registered tool.
//
// Per-tool role policy (SetToolRoles) is still enforced on the STDIO path,
// but only against the roles carried on the dispatch context. The default
// STDIO context (context.Background(), used by ServeSTDIO) carries no
// identity and therefore no roles. A host that has authenticated the local
// peer out-of-band can attach an identity/role-bearing context with
// ContextWithRoles and pass it to ServeSTDIOWithContext so role policy is
// evaluated against a real principal. Attaching a context is an enrichment
// hook — it is NOT an authentication gate, and it does not change the fact
// that the STDIO transport itself verifies nothing.
