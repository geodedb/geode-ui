// Package log is a thin structured-logging layer over the standard library's
// log/slog. It exposes a Logger interface with named severity levels (from
// deep-trace through trace, debug, info, warn, error, and fatal up to a
// dedicated security level) selectable by string, text or JSON output handlers,
// attribute and group decoration, and optional file rotation via lumberjack
// (see Config). A development mode makes DPanic panic after logging while the
// production default never crashes the process. It also provides a no-op Logger
// (NOOP) and a test-only logger that fails the test on Error/Fatal.
// Code generated by genapi; DO NOT EDIT.
package log

import (
	"context"
	"io"
	"log/slog"
	"os"
	"strings"
	"testing"

	"gopkg.in/natefinch/lumberjack.v2"
)

type Level int

func (t Level) String() string {
	switch t {
	case DTrace:
		return "deep-trace"
	case Trace:
		return "trace"
	case Debug:
		return "debug"
	case Info:
		return "info"
	case Warn:
		return "warn"
	case Error:
		return "error"
	case Fatal:
		return "fatal"
	default:
		return slog.Level(t).String()
	}
}

func (t Level) Level() slog.Level {
	return slog.Level(t)
}

const (
	DPanic Level = -20
	DTrace Level = -15
	Trace  Level = -6
	Debug  Level = -4
	Info   Level = 0
	Warn   Level = 4
	Error  Level = 8
	Crit   Level = 10
	Fatal  Level = 15
	Sec    Level = 20

	DefaultLevel Level = Error
)

func ParseLevel(level string) Level {
	level = strings.ToLower(strings.TrimSpace(level))

	switch level {
	case "debug-panic":
		return DPanic
	case "deep-trace":
		return DTrace
	case "trace":
		return Trace
	case "debug":
		return Debug
	case "info":
		return Info
	case "warn":
		return Warn
	case "error":
		return Error
	case "fatal":
		return Fatal
	default:
		return DefaultLevel
	}
}

type logger struct {
	ctx context.Context

	slogger *slog.Logger
	level   Level
	w       io.Writer
	group   string
	args    []slog.Attr

	addSource bool
	replAttr  func(groups []string, a slog.Attr) slog.Attr

	// development, when true, makes DPanic panic after logging. Default false
	// (production) so a dev-time assertion never crashes a deployed service.
	development bool

	handlerFn NewHandler
}

func Default() Logger {
	return &logger{
		slogger: slog.Default(),
		ctx:     context.Background(),
		w:       os.Stderr,
	}
}

func New(ctx context.Context, opts ...Option) Logger {
	out := &logger{
		ctx:       ctx,
		level:     DefaultLevel,
		w:         os.Stderr,
		handlerFn: TextHandler,
		slogger:   slog.Default(),
	}

	for _, opt := range opts {
		err := opt(out)
		if err != nil {
			return out
		}
	}

	// Re-Initialize Logger with updated Options
	out.slogger = out.init()
	return out
}

func (l *logger) init() *slog.Logger {
	options := &slog.HandlerOptions{
		Level:       l.level,
		AddSource:   l.addSource,
		ReplaceAttr: l.replAttr,
	}

	h := l.handlerFn(l.w, options)

	if len(l.args) > 0 {
		h = h.WithAttrs(l.args)
	}

	if l.group != "" {
		h = h.WithGroup(l.group)
	}

	return slog.New(h)
}

