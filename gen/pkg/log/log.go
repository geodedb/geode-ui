// TestLogger returns a Logger wired for use inside tests. It is exported (so
// other packages' _test.go can use it) and therefore lives in a non-_test.go
// file; the testing.Testing() guard + panic is an intentional misuse barrier
// that fails loudly if TestLogger is ever called from a production code path
// (QG-040: deliberate, not an accidental library panic).
func TestLogger(ctx context.Context, t *testing.T) Logger {
	if !testing.Testing() {
		panic("log.TestLogger called outside a test (testing.Testing()==false)")
	}

	level := Error
	ll := os.Getenv("LOG_LEVEL")
	if testing.Verbose() || ll != "" {
		level = Debug
		if ll != "" {
			level = ParseLevel(ll)
		}
	}

	f := Text
	if os.Getenv("LOG_FORMAT") == "json" {
		f = JSON
	}

	logger := New(
		ctx,
		WithLevel(level),
		WithFormat(f),
	)

	logger.SetDefault()

	t.Cleanup(func() {
		slog.SetDefault(slog.Default())
	})

	return &testlogger{
		Logger: logger,
		t:      t,
	}
}

type testlogger struct {
	Logger
	t *testing.T
}

func (l *testlogger) Error(msg string, args ...any) {
	args = append([]any{slog.String("test", l.t.Name())}, args...)
	l.Logger.Error(msg, args...)
	l.t.FailNow()
}

func (l *testlogger) Fatal(msg string, args ...any) {
	args = append([]any{slog.String("test", l.t.Name())}, args...)
	l.Logger.Fatal(msg, args...)
	l.t.FailNow()
}
